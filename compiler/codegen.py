"""Codegen: MICC AST -> .asm text for the micsim instruction set.

Contract (see the ABI reference in the project plan):
  - local slots: main numbers from slot 0 (slot 0 usable); callees number
    from slot 1 (slot 0 = OBJREF, params at 1..argc, declared vars follow).
  - main ends with 'halt'; callees end with 'ireturn' (bare return -> 0).
  - call sequence: 'bipush 0' (OBJREF placeholder) then args, then
    'invokevirtual <pool index>'.
  - branch offsets are relative to the branch instruction (assembler's job);
    codegen only emits labels.
  - literals -128..127 -> 'bipush'; others -> 'ldc_w' pool entry.
  - '*', '/', '%' lower to calls to the runtime functions mul/div/mod
    (provided by the runtime library, not part of the source program).
  - slots > 255 use 'wide iload/istore'.

Output format (locked by golden tests):
  '; generated by micc' header, blank line, methods in source order with
  main first, instructions indented 4 spaces, labels at column 0,
  '.const' section at the end (pool in first-use order).
"""

from lexer import CompileError
import ast_nodes as ast

RUNTIME_FUNCS = ('mul', 'div', 'mod')


class Codegen:
    def __init__(self, program):
        self.program = program
        self.func_table = {f.name: f for f in program.funcs}
        self.label_counter = 0
        self._is_main = False
        self.runtime_used = set()  # runtime functions the program needs
        self.pool = []            # ('int', value) | ('method', name)
        self.int_index = {}       # int value -> pool index
        self.method_index = {}    # method name -> pool index
        self.lines = []

    # ------------------------------------------------------------- helpers

    def _new_label(self):
        label = 'L%d' % self.label_counter
        self.label_counter += 1
        return label

    def _emit(self, line, indent=1):
        self.lines.append('    ' * indent + line if indent else line)

    def _int_entry(self, value):
        if value in self.int_index:
            return self.int_index[value]
        index = len(self.pool)
        self.pool.append(('int', value))
        self.int_index[value] = index
        return index

    def _method_entry(self, name):
        if name in self.method_index:
            return self.method_index[name]
        index = len(self.pool)
        self.pool.append(('method', name))
        self.method_index[name] = index
        return index

    def _load(self, slot):
        if slot > 255:
            self._emit('wide iload %d' % slot)
        else:
            self._emit('iload %d' % slot)

    def _store(self, slot):
        if slot > 255:
            self._emit('wide istore %d' % slot)
        else:
            self._emit('istore %d' % slot)

    # ------------------------------------------------------------- program

    def gen(self):
        self.lines = ['; generated by micc']
        main = self.func_table.get('main')
        self._gen_function(main)
        for f in self.program.funcs:
            if f is not main:
                self._gen_function(f)
        self._emit_consts()
        return '\n'.join(self.lines) + '\n'

    def _emit_consts(self):
        if not self.pool:
            return
        self.lines.append('')
        for kind, value in self.pool:
            self._emit('.const %d' % value if kind == 'int'
                       else '.const %s' % value, indent=0)

    # ----------------------------------------------------------- functions

    def _collect_slots(self, body, argc, frame_offset):
        """Assign one slot per declared variable, walking statements in
        textual order. Params are handled by the caller."""
        slots = {}
        next_slot = frame_offset + argc

        def walk(block):
            nonlocal next_slot
            for s in block.stmts:
                if isinstance(s, ast.VarDecl):
                    slots[s.name] = next_slot
                    next_slot += 1
                elif isinstance(s, ast.If):
                    walk_if(s.then_body)
                    if s.else_body is not None:
                        walk_if(s.else_body)
                elif isinstance(s, ast.While):
                    walk_if(s.body)
                elif isinstance(s, ast.Block):
                    walk(s)

        def walk_if(x):
            if isinstance(x, ast.Block):
                walk(x)
            else:
                walk(ast.Block([x]))

        walk(body)
        return slots

    def _gen_function(self, func):
        is_main = (func.name == 'main')
        self._is_main = is_main
        frame_offset = 0 if is_main else 1
        argc = len(func.params)

        # param slots (callees: 1..argc; main has no params)
        slots = {}
        for i, p in enumerate(func.params):
            slots[p] = frame_offset + i

        # declared locals
        slots.update(self._collect_slots(func.body, argc, frame_offset))
        declared = len(slots) - argc
        locals_count = declared

        self.lines.append('')
        self._emit('.method %s' % func.name, indent=0)
        if not is_main:
            self._emit('.params %d' % (1 + argc), indent=0)
        self._emit('.locals %d' % locals_count, indent=0)
        self._gen_stmt(func.body, slots)
        if is_main:
            self._emit('halt')
        else:
            # fall-through safety for bodies without a trailing return
            self._emit('bipush 0')
            self._emit('ireturn')

    # ---------------------------------------------------------- statements

    def _gen_stmt(self, stmt, slots):
        if isinstance(stmt, ast.Block):
            for s in stmt.stmts:
                self._gen_stmt(s, slots)

        elif isinstance(stmt, ast.VarDecl):
            if stmt.init is not None:
                self._gen_expr(stmt.init, slots)
                self._store(slots[stmt.name])

        elif isinstance(stmt, ast.Assign):
            self._gen_expr(stmt.expr, slots)
            self._store(slots[stmt.name])

        elif isinstance(stmt, ast.If):
            l_true = self._new_label()
            l_false = self._new_label()
            self._gen_cond(stmt.cond, l_true, l_false, slots)
            self._emit('%s:' % l_true, indent=0)
            self._gen_stmt(stmt.then_body, slots)
            if stmt.else_body is not None:
                l_end = self._new_label()
                self._emit('goto %s' % l_end)
                self._emit('%s:' % l_false, indent=0)
                self._gen_stmt(stmt.else_body, slots)
                self._emit('%s:' % l_end, indent=0)
            else:
                self._emit('%s:' % l_false, indent=0)

        elif isinstance(stmt, ast.While):
            l_start = self._new_label()
            l_body = self._new_label()
            l_end = self._new_label()
            self._emit('%s:' % l_start, indent=0)
            self._gen_cond(stmt.cond, l_body, l_end, slots)
            self._emit('%s:' % l_body, indent=0)
            self._gen_stmt(stmt.body, slots)
            self._emit('goto %s' % l_start)
            self._emit('%s:' % l_end, indent=0)

        elif isinstance(stmt, ast.Return):
            if stmt.expr is not None:
                self._gen_expr(stmt.expr, slots)
            if not self._is_main:
                self._emit('ireturn')

        elif isinstance(stmt, ast.ExprStmt):
            self._gen_expr(stmt.expr, slots)
            self._emit('pop')

        else:
            raise AssertionError('unhandled statement %r' % stmt)

    # --------------------------------------------------------- expressions

    def _gen_expr(self, expr, slots):
        if isinstance(expr, ast.IntLit):
            v = expr.value
            if not (-0x80000000 <= v <= 0xFFFFFFFF):
                raise CompileError(expr.line, 1,
                                   'integer literal %d out of 32-bit range' % v)
            if -128 <= v <= 127:
                self._emit('bipush %d' % v)
            else:
                self._emit('ldc_w %d' % self._int_entry(v))

        elif isinstance(expr, ast.Var):
            self._load(slots[expr.name])

        elif isinstance(expr, ast.Unary):
            if expr.op == '-':
                self._gen_expr(expr.operand, slots)
                self._emit('bipush 0')
                self._emit('swap')
                self._emit('isub')
            elif expr.op == '~':
                self._gen_expr(expr.operand, slots)
                self._emit('bipush -1')
                self._emit('swap')
                self._emit('isub')
            elif expr.op == '!':
                l_true = self._new_label()
                l_false = self._new_label()
                l_end = self._new_label()
                self._gen_cond(expr.operand, l_true, l_false, slots)
                self._emit('%s:' % l_true, indent=0)
                self._emit('bipush 1')
                self._emit('goto %s' % l_end)
                self._emit('%s:' % l_false, indent=0)
                self._emit('bipush 0')
                self._emit('%s:' % l_end, indent=0)
            else:
                raise AssertionError('unhandled unary op %r' % expr.op)

        elif isinstance(expr, ast.Binary):
            op = expr.op
            if op in ('<', '<=', '>', '>=', '==', '!=', '&&', '||'):
                l_true = self._new_label()
                l_false = self._new_label()
                l_end = self._new_label()
                self._gen_cond(expr, l_true, l_false, slots)
                self._emit('%s:' % l_true, indent=0)
                self._emit('bipush 1')
                self._emit('goto %s' % l_end)
                self._emit('%s:' % l_false, indent=0)
                self._emit('bipush 0')
                self._emit('%s:' % l_end, indent=0)
            elif op in ('+', '-', '&', '|'):
                self._gen_expr(expr.left, slots)
                self._gen_expr(expr.right, slots)
                self._emit({'+': 'iadd', '-': 'isub', '&': 'iand',
                            '|': 'ior'}[op])
            elif op in ('*', '/', '%'):
                self._gen_call_to_runtime(expr, slots)
            else:
                raise AssertionError('unhandled binary op %r' % op)

        elif isinstance(expr, ast.Call):
            self._gen_call(expr, slots)

        else:
            raise AssertionError('unhandled expression %r' % expr)

    def _gen_call_to_runtime(self, expr, slots):
        """a * b  ->  bipush 0; a; b; invokevirtual <mul>"""
        func = {'*': 'mul', '/': 'div', '%': 'mod'}[expr.op]
        self.runtime_used.add(func)
        self._emit('bipush 0')
        self._gen_expr(expr.left, slots)
        self._gen_expr(expr.right, slots)
        self._emit('invokevirtual %d' % self._method_entry(func))

    def _gen_call(self, call, slots):
        func = self.func_table.get(call.name)
        if func is None:
            raise CompileError(call.line, 1,
                               "call to undefined function '%s'" % call.name)
        if len(call.args) != len(func.params):
            raise CompileError(call.line, 1,
                               "function '%s' expects %d arguments, got %d"
                               % (call.name, len(func.params), len(call.args)))
        self._emit('bipush 0')
        for a in call.args:
            self._gen_expr(a, slots)
        self._emit('invokevirtual %d' % self._method_entry(call.name))

    def _gen_cond(self, expr, l_true, l_false, slots):
        """Branch to l_true/l_false based on expr's truth value."""
        if isinstance(expr, ast.Unary) and expr.op == '!':
            self._gen_cond(expr.operand, l_false, l_true, slots)

        elif isinstance(expr, ast.Binary):
            op = expr.op
            if op == '&&':
                l_mid = self._new_label()
                self._gen_cond(expr.left, l_mid, l_false, slots)
                self._emit('%s:' % l_mid, indent=0)
                self._gen_cond(expr.right, l_true, l_false, slots)
            elif op == '||':
                l_mid = self._new_label()
                self._gen_cond(expr.left, l_true, l_mid, slots)
                self._emit('%s:' % l_mid, indent=0)
                self._gen_cond(expr.right, l_true, l_false, slots)
            elif op in ('<', '<=', '>', '>=', '==', '!='):
                if op == '<':
                    self._gen_expr(expr.left, slots)
                    self._gen_expr(expr.right, slots)
                    self._emit('isub')
                    self._emit('iflt %s' % l_true)
                    self._emit('goto %s' % l_false)
                elif op == '>':
                    self._gen_expr(expr.right, slots)
                    self._gen_expr(expr.left, slots)
                    self._emit('isub')
                    self._emit('iflt %s' % l_true)
                    self._emit('goto %s' % l_false)
                elif op == '<=':
                    self._gen_expr(expr.right, slots)
                    self._gen_expr(expr.left, slots)
                    self._emit('isub')
                    self._emit('iflt %s' % l_false)
                    self._emit('goto %s' % l_true)
                elif op == '>=':
                    self._gen_expr(expr.left, slots)
                    self._gen_expr(expr.right, slots)
                    self._emit('isub')
                    self._emit('iflt %s' % l_false)
                    self._emit('goto %s' % l_true)
                elif op == '==':
                    self._gen_expr(expr.left, slots)
                    self._gen_expr(expr.right, slots)
                    self._emit('isub')
                    self._emit('ifeq %s' % l_true)
                    self._emit('goto %s' % l_false)
                else:  # '!='
                    self._gen_expr(expr.left, slots)
                    self._gen_expr(expr.right, slots)
                    self._emit('isub')
                    self._emit('ifeq %s' % l_false)
                    self._emit('goto %s' % l_true)
            else:
                # arithmetic etc. as a condition: nonzero is true
                self._gen_expr(expr, slots)
                self._emit('ifeq %s' % l_false)
                self._emit('goto %s' % l_true)

        else:
            self._gen_expr(expr, slots)
            self._emit('ifeq %s' % l_false)
            self._emit('goto %s' % l_true)


def gen(program):
    return Codegen(program).gen()
