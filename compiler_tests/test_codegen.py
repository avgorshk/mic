def main():
    failed = 0
    for name, ok, msg in RESULTS:
        if ok:
            print('[PASS] %s' % name)
        else:
            print('[FAIL] %s: %s' % (name, msg))
            failed += 1
    print('Total: %d, failed: %d' % (len(RESULTS), failed))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
