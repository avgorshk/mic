"""Unit tests for the MICC codegen (compiler/codegen.py).

Run: python compiler_tests/test_codegen.py
Golden tests assert the exact .asm text for representative programs.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                '..', 'compiler'))
from lexer import Lexer, CompileError  # noqa: E402
from parser import parse  # noqa: E402
from codegen import gen  # noqa: E402

RESULTS = []


def check(name, fn):
    try:
        fn()
        RESULTS.append((name, True, ''))
    except Exception as e:
        RESULTS.append((name, False, '%s: %s' % (type(e).__name__, e)))


def gen_src(source):
    return gen(parse(Lexer(source).tokenize()))


def expect_error(source, needle):
    try:
        gen_src(source)
    except CompileError as e:
        assert needle in e.msg, "error '%s' does not contain '%s'" % (e.msg, needle)
        return
    raise AssertionError('expected CompileError containing %r, got no error' % needle)


FIB_SRC = '''\
int fib(int n) {
    if (n < 2)
        return n;
    return fib(n - 1) + fib(n - 2);
}

int main() {
    int r = fib(10);
    return r;
}
'''

FIB_ASM = '''\
; generated by micc

.method main
.locals 1
    bipush 0
    bipush 10
    invokevirtual 0
    istore 0
    iload 0
    halt

.method fib
.params 2
.locals 0
    iload 1
    bipush 2
    isub
    iflt L0
    goto L1
L0:
    iload 1
    ireturn
L1:
    bipush 0
    iload 1
    bipush 1
    isub
    invokevirtual 0
    bipush 0
    iload 1
    bipush 2
    isub
    invokevirtual 0
    iadd
    ireturn
    bipush 0
    ireturn

.const fib
'''


def test_fib():
    assert gen_src(FIB_SRC) == FIB_ASM, gen_src(FIB_SRC)


